-- DBDock sample data for Firebird (3.0 or newer).
-- Runs once, when the database is created.
-- Accented letters and other non-ASCII characters test encoding.

CREATE TABLE customers (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(50)  NOT NULL,
    last_name  VARCHAR(80)  NOT NULL,
    email      VARCHAR(120) NOT NULL UNIQUE,
    city       VARCHAR(80),
    notes      VARCHAR(200),
    created_at TIMESTAMP    DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE orders (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id INTEGER       NOT NULL REFERENCES customers (id),
    product     VARCHAR(120)  NOT NULL,
    quantity    INTEGER       NOT NULL CHECK (quantity > 0),
    price       NUMERIC(10,2) NOT NULL,
    order_date  DATE          NOT NULL
);

CREATE VIEW v_customer_summary AS
SELECT c.id AS customer_id,
       c.first_name,
       c.last_name,
       c.city,
       COUNT(o.id) AS order_count,
       COALESCE(SUM(o.quantity * o.price), 0) AS order_total
FROM customers c
LEFT JOIN orders o ON o.customer_id = c.id
GROUP BY c.id, c.first_name, c.last_name, c.city;

